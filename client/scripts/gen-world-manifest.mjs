// Generates src/offline/world.manifest.js: the pinned list of world-language packs (OPUS-MT / Marian, int8 ONNX)
// that devices download straight from Hugging Face. Nothing here goes through server/models.
//
//   node scripts/gen-world-manifest.mjs            (re)write the manifest from Hugging Face
//
// Every pack is pinned to a commit and every file to its exact byte size (re-checked with a ranged request,
// the same way server/scripts/fetch-models.mjs does), because the client rejects a download of any other size.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, '../src/offline/world.manifest.js');

// Languages that have a Xenova/opus-mt model in BOTH directions with English (verified to exist).
const LANGS = ['af', 'ar', 'cs', 'da', 'de', 'es', 'fi', 'fr', 'hu', 'id', 'it', 'nl', 'ru', 'sv', 'uk', 'vi', 'zh'];
// [path in the repo, name used for the cache key]
const FILES = [
  ['onnx/encoder_model_int8.onnx', 'encoder_model_int8.onnx'],
  ['onnx/decoder_model_merged_int8.onnx', 'decoder_model_merged_int8.onnx'],
  ['tokenizer.json', 'tokenizer.json'],
  ['tokenizer_config.json', 'tokenizer_config.json'],
  ['config.json', 'config.json'],
];

const api = async (u) => {
  const res = await fetch(u);
  if (!res.ok) throw new Error(`${u}: HTTP ${res.status}`);
  return res.json();
};

async function remoteSize(url) {
  const res = await fetch(url, { headers: { Range: 'bytes=0-0' } });
  await res.body?.cancel();
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const range = res.headers.get('content-range');
  return range ? Number(range.split('/')[1]) : Number(res.headers.get('content-length'));
}

async function pack(from, to) {
  const repo = `Xenova/opus-mt-${from}-${to}`;
  const info = await api(`https://huggingface.co/api/models/${repo}?blobs=true`);
  const sha = info.sha;
  const files = [];
  for (const [rel, name] of FILES) {
    const sib = info.siblings.find((s) => s.rfilename === rel);
    if (!sib) throw new Error(`${repo} has no ${rel}`);
    const size = await remoteSize(`https://huggingface.co/${repo}/resolve/${sha}/${rel}`);
    if (sib.size && sib.size !== size) throw new Error(`${repo}/${rel}: API says ${sib.size}, server says ${size}`);
    files.push({ name, path: rel, size });
  }
  return { id: `mt-${from}-${to}`, from, to, repo, sha, files };
}

const jobs = [];
for (const l of LANGS) jobs.push(['en', l], [l, 'en']);
const packs = [];
for (let i = 0; i < jobs.length; i += 6) {
  const batch = await Promise.all(jobs.slice(i, i + 6).map(([a, b]) => pack(a, b)));
  packs.push(...batch);
  console.log(`${packs.length}/${jobs.length}`);
}

const body = `// GENERATED by scripts/gen-world-manifest.mjs. Do not edit by hand.
// World-language packs (OPUS-MT / Marian, int8 ONNX, Apache-2.0 originals by Helsinki-NLP, ONNX export by Xenova).
export const WORLD_LANGS = ${JSON.stringify(LANGS)};

export const WORLD_MANIFEST = ${JSON.stringify(packs, null, 1)};
`;
fs.writeFileSync(OUT, body);
const total = packs.reduce((n, p) => n + p.files.reduce((m, f) => m + f.size, 0), 0);
console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${packs.length} packs, ${(total / 1e9).toFixed(2)} GB in total`);
